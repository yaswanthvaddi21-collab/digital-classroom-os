#!/usr/bin/env node
// Lists every production dependency shipped in the web app with its licence, writes
// docs/THIRD_PARTY_NOTICES.md, and exits non-zero if any licence is outside the allow-list.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ALLOWED = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'OFL-1.1', 'Unlicense', 'CC0-1.0', 'BlueOak-1.0.0', 'Python-2.0', 'Zlib']);
// Dual-licensed packages where we use the permissive option.
const DUAL_OK = { '(MIT OR GPL-3.0-or-later)': 'MIT', '(MPL-2.0 OR Apache-2.0)': 'Apache-2.0', '(MIT OR Apache-2.0)': 'MIT', '(MIT AND Zlib)': 'MIT AND Zlib', '(MIT OR CC0-1.0)': 'MIT', 'MIT OR SEE LICENSE IN FEEL-FREE.md': 'MIT' };

const tree = JSON.parse(execSync('npm ls --all --omit=dev --json -w @dcos/web', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));
const seen = new Map();
const walk = (deps = {}) => {
  for (const [name, info] of Object.entries(deps)) {
    if (name.startsWith('@dcos/')) {
      walk(info.dependencies);
      continue;
    }
    // Optional peers that aren't installed appear without a version; nothing ships for them.
    if (!info.version) continue;
    const key = `${name}@${info.version}`;
    if (seen.has(key)) continue;
    let license = 'UNKNOWN';
    try {
      const pkg = JSON.parse(readFileSync(join(info.path ?? join('node_modules', name), 'package.json'), 'utf8'));
      license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses?.map((l) => l.type).join(' OR ') || 'UNKNOWN');
    } catch {}
    seen.set(key, { name, version: info.version, license });
    walk(info.dependencies);
  }
};
walk(tree.dependencies);

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const effective = (l) => DUAL_OK[l] ?? l;
const bad = rows.filter((r) => !effective(r.license).split(/ AND /).every((p) => ALLOWED.has(p.replace(/[()]/g, ''))));

const counts = {};
rows.forEach((r) => (counts[r.license] = (counts[r.license] ?? 0) + 1));
const md = [
  '# Third-party notices',
  '',
  `Generated by \`npm run licenses\` on ${new Date().toISOString().slice(0, 10)}. Production dependencies of the web app (shared by the desktop and Android shells).`,
  '',
  '## Licence summary',
  '',
  '| Licence | Packages |',
  '|---|---|',
  ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, c]) => `| ${l} | ${c} |`),
  '',
  `Packages needing review: ${bad.length ? bad.map((b) => `${b.name}@${b.version} (${b.license})`).join(', ') : 'none'}.`,
  '',
  '## Packages',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
];
writeFileSync('docs/THIRD_PARTY_NOTICES.md', md.join('\n'));
console.log(`${rows.length} production packages. Licences: ${JSON.stringify(counts)}`);
if (bad.length) {
  console.error('Licences outside policy:', bad);
  process.exit(1);
}
