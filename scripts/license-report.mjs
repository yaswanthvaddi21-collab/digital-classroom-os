#!/usr/bin/env node
// Lists every production dependency recorded in package-lock.json with its licence, writes
// docs/THIRD_PARTY_NOTICES.md, and exits non-zero if any licence is outside the allow-list.
// Reads the lock file rather than node_modules so nested copies are checked as installed (audit DEPE-6).
import { readFileSync, writeFileSync } from 'node:fs';

const ALLOWED = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'OFL-1.1', 'Unlicense', 'CC0-1.0', 'BlueOak-1.0.0', 'Python-2.0', 'Zlib']);
// Dual-licensed packages where we use the permissive option. Exact strings only; add one per reviewed package.
const DUAL_OK = {
  '(MIT OR GPL-3.0-or-later)': 'MIT', // jszip
  '(MPL-2.0 OR Apache-2.0)': 'Apache-2.0', // dompurify (aliased out of the build, still in the lock)
  '(MIT OR Apache-2.0)': 'MIT',
  '(MIT AND Zlib)': 'MIT AND Zlib', // pako
  '(MIT OR CC0-1.0)': 'MIT',
  'MIT OR SEE LICENSE IN FEEL-FREE.md': 'MIT', // rgbcolor
};

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const rows = new Map();
for (const [path, pkg] of Object.entries(lock.packages ?? {})) {
  // Production packages only: not dev-only, not workspace links, not the root.
  if (!path.startsWith('node_modules/') && !path.includes('/node_modules/')) continue;
  if (pkg.dev || pkg.devOptional || pkg.link) continue;
  const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
  if (name.startsWith('@dcos/') || name.startsWith('@types/')) continue;
  const key = `${name}@${pkg.version}`;
  if (!rows.has(key)) rows.set(key, { name, version: pkg.version, license: pkg.license ?? 'UNKNOWN' });
}

const list = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const effective = (l) => DUAL_OK[l] ?? l;
const bad = list.filter((r) => !effective(r.license).split(/ AND /).every((p) => ALLOWED.has(p.replace(/[()]/g, ''))));
const pro = list.filter((r) => r.name.startsWith('@tiptap-pro/'));

const counts = {};
list.forEach((r) => (counts[r.license] = (counts[r.license] ?? 0) + 1));
const md = [
  '# Third-party notices',
  '',
  'Generated by `npm run licenses` from package-lock.json: every production dependency installed for the app (dev and test tools excluded).',
  '',
  '## Licence summary',
  '',
  '| Licence | Packages |',
  '|---|---|',
  ...Object.entries(counts).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([l, c]) => `| ${l} | ${c} |`),
  '',
  `Packages needing review: ${bad.length ? bad.map((b) => `${b.name}@${b.version} (${b.license})`).join(', ') : 'none'}.`,
  '',
  '## Packages',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...list.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
];
writeFileSync('docs/THIRD_PARTY_NOTICES.md', md.join('\n'));
console.log(`${list.length} production packages. Licences: ${JSON.stringify(counts)}`);
if (pro.length) {
  console.error('Paid Tiptap Pro packages are not allowed:', pro.map((p) => p.name));
  process.exit(1);
}
if (bad.length) {
  console.error('Licences outside policy:', bad);
  process.exit(1);
}
